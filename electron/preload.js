// Bridge between the sandboxed UI and the main process. Callbacks never receive
// the IpcRendererEvent (it would expose ipcRenderer to the page).
const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("inventory", {
  read: () => ipcRenderer.invoke("inventory:read"),
  rescan: () => ipcRenderer.invoke("inventory:rescan"),
  export: () => ipcRenderer.invoke("inventory:export"),
  import: () => ipcRenderer.invoke("inventory:import"),
  switchToOwn: () => ipcRenderer.invoke("inventory:switchToOwn"),
  reveal: (name) => ipcRenderer.invoke("item:reveal", name),
  openUrl: (url) => ipcRenderer.invoke("url:open", url),
  saveScript: (content, name) => ipcRenderer.invoke("script:save", { content, name }),
  runScript: (content, name) => ipcRenderer.invoke("script:run", { content, name }),
  history: () => ipcRenderer.invoke("history:list"),
  exportBrewfile: () => ipcRenderer.invoke("brewfile:export"),
  openSettings: (pane) => ipcRenderer.invoke("settings:open", pane),
  revealPath: (p) => ipcRenderer.invoke("path:reveal", p),
  notes: () => ipcRenderer.invoke("notes:get"),
  setNote: (key, value) => ipcRenderer.invoke("notes:set", key, value),
  savePdf: (html, name) => ipcRenderer.invoke("report:pdf", { html, name }),
  onNav: (cb) => ipcRenderer.on("nav:go", (_e, page) => cb(page)),
  getSettings: () => ipcRenderer.invoke("settings:get"),
  setSettings: (patch) => ipcRenderer.invoke("settings:set", patch),
  onSettings: (cb) => ipcRenderer.on("settings:changed", (_e, s) => cb(s)),
  cancelScan: () => ipcRenderer.invoke("scan:cancel"),
  clearHistory: () => ipcRenderer.invoke("history:clear"),
  clearNotes: () => ipcRenderer.invoke("notes:clear"),
  openDataDir: () => ipcRenderer.invoke("data:open"),
  exportCsv: () => ipcRenderer.invoke("csv:export"),
  exportDotfiles: () => ipcRenderer.invoke("dotfiles:export"),
  listMacs: () => ipcRenderer.invoke("macs:list"),
  openMac: (file) => ipcRenderer.invoke("macs:open", file),
  syncNow: () => ipcRenderer.invoke("sync:now"),
  chooseSyncDir: () => ipcRenderer.invoke("sync:choose"),
  openSyncDir: () => ipcRenderer.invoke("sync:open"),
  openAutoDir: (kind) => ipcRenderer.invoke("autodir:open", kind),
  savePdfAuto: (html) => ipcRenderer.invoke("report:pdfAuto", { html }),
  onReportAuto: (cb) => ipcRenderer.on("report:auto", () => cb()),
  onReportRequest: (cb) => ipcRenderer.on("report:request", () => cb()),
  accent: () => ipcRenderer.invoke("theme:accent"),
  onAccent: (cb) => ipcRenderer.on("theme:accent", (_e, c) => cb(c)),
  onFocus: (cb) => ipcRenderer.on("window:focus", (_e, f) => cb(f)),
  onScanStarted: (cb) => ipcRenderer.on("scan:started", (_e, p) => cb(p)),
  onScanProgress: (cb) => ipcRenderer.on("scan:progress", (_e, p) => cb(p)),
  onScanDone: (cb) => ipcRenderer.on("scan:done", (_e, p) => cb(p)),
  onInventoryChanged: (cb) => ipcRenderer.on("inventory:changed", () => cb()),
  onToast: (cb) => ipcRenderer.on("toast", (_e, p) => cb(p)),
});
